/** Text in the person's language, with {values} put in. */
export function tr(lang, text, vars) {
  let s = langOf(lang) === 'ru' ? (RU[text] ?? text) : text;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

/** Both languages of a text (incoming Telegram buttons may be pressed in either). */
export const both = (text) => [text, RU[text] ?? text];

/** The language of a person by id. */
export const userLang = (db, id) => langOf(db.prepare('SELECT lang FROM users WHERE id = ?').get(id)?.lang);
